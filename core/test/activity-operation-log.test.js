const test = require('node:test');
const assert = require('node:assert/strict');
const { withActivityOperationLog } = require('../src/services/activity-operation-log');
test('shared activity outcome logger covers success, skip and failure without request data', async () => {
  const logs = [];
  const log = (...args) => logs.push(args);
  const reply = { ok: true, secret: 'private-response' };
  const operation = withActivityOperationLog(async () => reply, '领取奖励', log);
  assert.equal(await operation({ token: 'private-request' }), reply);
  assert.equal(logs[0][2].result, 'success');
  const skip = withActivityOperationLog(async () => ({ claimed: false }), '领取奖励', log);
  await skip();
  assert.equal(logs[1][2].result, 'skip');
  const error = new Error('资源不足');
  const fail = withActivityOperationLog(async () => { throw error; }, () => '送出爱心', log);
  await assert.rejects(fail(), e => e === error);
  assert.equal(logs[2][2].result, 'error');
  assert.equal(error.activityOperationLogged, true);
  assert.match(logs[2][1], /送出爱心失败：资源不足/);
  assert.ok(logs.every(entry => entry[0] === '活动' && entry[2].module === 'activity'));
  assert.ok(!JSON.stringify(logs).includes('private-'));
});
